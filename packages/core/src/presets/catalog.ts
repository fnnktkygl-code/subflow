export function searchPresetCatalog(query: string, countryCode?: string, category?: string): CatalogService[] {
  const normQuery = (query || '').toLowerCase().trim();
  const targetCountry = (countryCode || 'FR').toUpperCase();

  return COMPLETE_SUBSCRIPTION_CATALOG.filter((item) => {
    if (category && category !== 'All' && item.category !== category) {
      return false;
    }
    if (normQuery.length > 0) {
      return (
        item.name.toLowerCase().includes(normQuery) ||
        item.domain.toLowerCase().includes(normQuery) ||
        item.category.toLowerCase().includes(normQuery)
      );
    }
    if (targetCountry) {
      return item.popularIn.includes(targetCountry) || item.popularIn.includes('GLOBAL');
    }
    return true;
  });
}
